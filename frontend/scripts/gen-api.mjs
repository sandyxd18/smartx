// Generate src/api/schema.d.ts from the backend's OpenAPI schema.
// The schema is produced by importing the FastAPI app, so no server needs to run.
//   node scripts/gen-api.mjs          write the file
//   node scripts/gen-api.mjs --check  fail if the committed file is out of date
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const backendDir = resolve(here, "../../backend");
const outFile = resolve(here, "../src/api/schema.d.ts");
const check = process.argv.includes("--check");

const dump = spawnSync("uv", ["run", "--quiet", "python", "-m", "app.openapi_dump"], {
  cwd: backendDir,
  encoding: "utf-8",
  maxBuffer: 16 * 1024 * 1024,
});
if (dump.status !== 0) {
  console.error(dump.error?.message ?? dump.stderr);
  console.error("Gagal membaca skema OpenAPI dari backend (perlu `uv` dan backend/).");
  process.exit(1);
}

const ast = await openapiTS(JSON.parse(dump.stdout));
const header = "// Generated by `npm run gen:api` from the backend OpenAPI schema. Do not edit.\n\n";
const content = header + astToString(ast);

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf-8").replaceAll("\r\n", "\n") : "";
  if (current !== content) {
    console.error("src/api/schema.d.ts tidak sesuai dengan API backend. Jalankan `npm run gen:api`.");
    process.exit(1);
  }
  console.log("schema.d.ts up to date");
} else {
  writeFileSync(outFile, content);
  console.log(`wrote ${outFile}`);
}
